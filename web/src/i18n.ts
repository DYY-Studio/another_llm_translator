export function translate(
  key: string,
  language: Language,
  values: Record<string, string | number> = {},
): string {
  const template = messages[language][key] ?? messages["zh-CN"][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

